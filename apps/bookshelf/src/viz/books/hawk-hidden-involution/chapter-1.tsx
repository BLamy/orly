// Source: hawk_key_recovery.pdf, sections 2 through 4.
// Persistent object: the public Gram matrix is reflected by tau until its hidden cocycle appears as a public shortest vector.
import { CAMERA_HOME, Camera, Timeline, cameraInterp, colors, ease } from '../../core';
import type { CameraState, SceneState } from '../../core';
import { Arrow, Chip, Panel, ResearchTitle, clamp01, mono } from '../../book-components/research';

const LATTICE = Array.from({ length: 81 }, (_, i) => ({ x: i % 9 - 4, y: Math.floor(i / 9) - 4 }));
const LATTICE_CX = 960;
const LATTICE_CY = 388;
// Plain SVG text for formulas: KaTeX's MathML fallback renders doubled when its stylesheet is absent.
const math = "'Times New Roman', Georgia, serif";

export function buildScene() {
  const tl = new Timeline();
  const cam = tl.channel<CameraState>('cam', CAMERA_HOME, cameraInterp);
  const gramU = tl.channel('gramU', 0);
  const secretU = tl.channel('secretU', 0);
  const tauU = tl.channel('tauU', 0);
  const cocycleU = tl.channel('cocycleU', 0);
  const constraintsU = tl.channel('constraintsU', 0);
  const latticeU = tl.channel('latticeU', 0);
  const shortestU = tl.channel('shortestU', 0);
  let t = 0.4;
  t = tl.caption({ at: t, dur: 6.2, text: 'The signature scheme publishes a Gram matrix made from a short secret basis. Recover any equivalent basis, and you can sign.' });
  tl.tween(gramU, 1, { at: 0.8, dur: 1.0, ease: ease.enter });
  tl.tween(secretU, 1, { at: 1.6, dur: 1.0, ease: ease.draw });
  t = tl.hold(t, 0);
  t = tl.caption({ at: t, dur: 6.3, text: 'The power-of-two cyclotomic field has a second involution: send zeta to minus zeta, distinct from complex conjugation.' });
  tl.tween(tauU, 1, { at: t - 5.2, dur: 1.3, ease: ease.move });
  tl.tween(cam, { x: 640, y: 340, k: 1.03 }, { at: t - 5.0, dur: 1.2, ease: ease.move });
  t = tl.hold(t, 0);
  t = tl.caption({ at: t, dur: 6.3, text: 'Compare the secret basis with its reflected copy. Their ratio is a cocycle: a hidden automorphism built from the secret.' });
  tl.tween(cocycleU, 1, { at: t - 5.2, dur: 1.0, ease: ease.pop });
  t = tl.hold(t, 0);
  t = tl.caption({ at: t, dur: 6.4, text: 'Although the cocycle contains the secret, it satisfies two linear relations involving only the public Gram matrix and its reflected copy.' });
  tl.tween(constraintsU, 1, { at: t - 5.3, dur: 1.2, ease: ease.draw });
  t = tl.hold(t, 0);
  t = tl.caption({ at: t, dur: 6.3, text: 'The integer solutions form a public lattice of rank n. The true cocycle is guaranteed to lie inside it.' });
  tl.tween(latticeU, 1, { at: t - 5.2, dur: 1.6, ease: ease.enter });
  tl.tween(cam, CAMERA_HOME, { at: t - 5.0, dur: 1.2, ease: ease.move });
  t = tl.hold(t, 0);
  t = tl.caption({ at: t, dur: 6.3, text: 'Its determinant is one, so the public quadratic form gives it the minimum possible length, exactly n divided by four.' });
  tl.tween(shortestU, 1, { at: t - 5.2, dur: 1.0, ease: ease.pop });
  t = tl.hold(t, 0);
  t = tl.caption({ at: t, dur: 5.8, text: 'Key recovery has become a shortest-vector search in a public rank-n lattice. The remaining question is why that search needs only half the dimension.' });
  tl.tween(cam, CAMERA_HOME, { at: t - 5.0, dur: 1.2, ease: ease.move });
  return { tl, cam, gramU, secretU, tauU, cocycleU, constraintsU, latticeU, shortestU };
}
const scene = buildScene();

export function Render({ s }: { s: SceneState }) {
  const tau = s.get(scene.tauU);
  const lat = s.get(scene.latticeU);
  const gramU = s.get(scene.gramU);
  const tauU = s.get(scene.tauU);
  const cocycleU = s.get(scene.cocycleU);
  const constraintsU = s.get(scene.constraintsU);
  const shortestU = s.get(scene.shortestU);
  // Glossary rows build up as each term first appears on screen.
  const gloss = [
    { x: 70, y: 560, term: 'Gram matrix Q = B*B', rest: ': public inner products of the basis', opacity: gramU, color: colors.ACCENT },
    { x: 680, y: 560, term: 'involution τ', rest: ': a map that undoes itself (τ∘τ = id)', opacity: tauU, color: colors.WARM },
    { x: 70, y: 582, term: 'cocycle Vτ = B⁻¹τ(B)', rest: ': a hidden automorphism built from the secret', opacity: cocycleU, color: colors.POSITIVE },
    { x: 680, y: 582, term: 'cyclotomic field Q(ζ)', rest: ': generated by a root of unity ζ', opacity: tauU, color: colors.WARM },
    { x: 70, y: 604, term: 'rank-n lattice', rest: ': integer solutions in n dimensions', opacity: s.get(scene.latticeU), color: colors.POSITIVE },
    { x: 680, y: 604, term: 'shortest vector', rest: ': least length any nonzero lattice point has', opacity: shortestU, color: colors.POSITIVE },
  ];
  return (
    <g>
      <ResearchTitle kicker="The Hidden Involution · 1" title="A symmetry inside the public key" />
      <Camera {...s.get(scene.cam)}>
        <Panel x={70} y={145} w={470} h={365} opacity={gramU} accent={colors.ACCENT}>
          <text x={305} y={180} textAnchor="middle" fill={colors.MUTED} fontFamily={mono} fontSize={14}>public key</text>
          <text x={305} y={240} textAnchor="middle" fill={colors.TEXT} fontFamily={math} fontStyle="italic" fontSize={28}>Q = B*B</text>
          <g opacity={s.get(scene.secretU)}>
            <path d="M 185 380 L 305 280 L 425 380" fill="none" stroke={colors.SECONDARY} strokeWidth={5} />
            <text x={305} y={266} textAnchor="middle" fill={colors.SECONDARY} fontFamily={mono} fontSize={14}>short secret basis B</text>
          </g>
          <g opacity={tau}>
            <path d="M 185 380 L 305 470 L 425 380" fill="none" stroke={colors.WARM} strokeWidth={5} />
            <text x={305} y={498} textAnchor="middle" fill={colors.WARM} fontFamily={mono} fontSize={14}>τ(B) · ζ ↦ −ζ</text>
          </g>
        </Panel>
        {/* The chip sits centred over the arrow it labels, in the gap between the two panels. */}
        <Arrow x1={548} y1={340} x2={702} y2={340} reveal={cocycleU} color={colors.POSITIVE} />
        <Chip x={625} y={314} text="Vτ = B⁻¹τ(B)" opacity={cocycleU} color={colors.POSITIVE} width={150} />
        {/* Panel stays opaque so the header is visible from the start; its contents fade in per beat. */}
        <Panel x={710} y={145} w={500} h={365} opacity={1} accent={colors.POSITIVE}>
          <text x={960} y={180} textAnchor="middle" fill={colors.MUTED} fontFamily={mono} fontSize={14}>unknown cocycle Vτ</text>
          {/* Dashed placeholders show the two unknown relations before they are established. */}
          {[
            { y: 198, label: 'relation 1', eq: 'Yτ(Y) = I' },
            { y: 250, label: 'relation 2', eq: 'Y*QY = τ(Q)' },
          ].map((r) => (
            <g key={r.label}>
              <rect x={738} y={r.y} width={444} height={40} rx={8} fill="none" stroke={colors.MUTED} strokeDasharray="5 5" strokeWidth={1.2} opacity={1 - constraintsU} />
              <text x={752} y={r.y + 25} fill={colors.MUTED} fontFamily={mono} fontSize={14} opacity={1 - constraintsU}>{r.label}: ?</text>
              <g opacity={constraintsU}>
                <rect x={738} y={r.y} width={444} height={40} rx={8} fill={colors.POSITIVE} fillOpacity={0.1} stroke={colors.POSITIVE} strokeWidth={1.2} />
                <text x={752} y={r.y + 25} fill={colors.MUTED} fontFamily={mono} fontSize={14}>{r.label}</text>
                <text x={1000} y={r.y + 27} textAnchor="middle" fill={colors.TEXT} fontFamily={math} fontStyle="italic" fontSize={22}>{r.eq}</text>
              </g>
            </g>
          ))}
          {/* The lattice grid is faintly visible from the start and lights up as the lattice is established. */}
          <g opacity={0.2 + 0.8 * lat}>
            {LATTICE.map((p, i) => <circle key={i} cx={LATTICE_CX + p.x * 40} cy={LATTICE_CY + p.y * 22} r={3.5} fill={colors.MUTED} />)}
          </g>
          <g opacity={shortestU}>
            <circle cx={LATTICE_CX} cy={LATTICE_CY} r={18} fill={colors.POSITIVE} fillOpacity={0.25} stroke={colors.POSITIVE} strokeWidth={3} />
            <text x={LATTICE_CX} y={500} textAnchor="middle" fill={colors.POSITIVE} fontFamily={mono} fontSize={14}>Vτ · shortest, length n/4</text>
          </g>
        </Panel>
      </Camera>
      <g>
        {gloss.map((g) => (
          <text key={g.term} x={g.x} y={g.y} fill={colors.TEXT} fontFamily={mono} fontSize={14} opacity={g.opacity}>
            <tspan fill={g.color} fontWeight={700}>{g.term}</tspan>
            {g.rest}
          </text>
        ))}
      </g>
    </g>
  );
}
export const vizScene = () => scene;
