// The film's credits, built from what the pipeline actually recorded (never typed by hand): every model and tool
// that made a part of the film, plus a strudel.cc link for every music cue (the cue's exact Strudel source in the
// URL fragment: https://strudel.cc/#<encodeURIComponent(base64(utf-8 code))>, verified to load byte-for-byte).
//
//   buildCredits(P, { slug, cues, voice }) -> { version, slug, roles: [{ role, credit, detail? }], cues: [...] }
//
// Written by publish.mjs to public/generated/<slug>/credits.json (the player's Credits section) and to
// apps/bookshelf/src/viz/films/<slug>/credits.json (the film's own end-credits card reads it).
import fs from 'node:fs';
import path from 'node:path';
import { readJson } from './paths.mjs';

/** a strudel.cc link that opens the REPL with this exact code */
export const strudelLink = (code) => `https://strudel.cc/#${encodeURIComponent(Buffer.from(code, 'utf8').toString('base64'))}`;

/** every distinct `"model": "<id>"` recorded anywhere in a JSON document */
function modelsIn(doc) {
  const out = new Set();
  JSON.stringify(doc ?? {}, (k, v) => {
    if (k === 'model' && typeof v === 'string') out.add(v);
    return v;
  });
  return out;
}

const MODEL_NAMES = {
  'claude-opus-5-5': 'Claude Opus 5.5 (Anthropic)',
  eleven_multilingual_v2: 'ElevenLabs Multilingual v2',
  eleven_v3: 'ElevenLabs v3',
  eleven_v4: 'ElevenLabs v4',
  scribe_v1: 'ElevenLabs Scribe',
};
const nice = (m) => MODEL_NAMES[m] ?? m;

/** the cue's title from its source header: // m03 "Clue Two: A Knob That Turns" (…) */
const cueTitle = (code, id) => code.match(new RegExp(`^//\\s*${id}\\s+"([^"]+)"`, 'm'))?.[1] ?? null;

export function buildCredits(P, { slug, cues, voice }) {
  const film = readJson(path.join(P.dir, 'film.json'), {});
  const stt = readJson(path.join(P.narration.dir, 'stt.json'), null);
  const recorded = new Set([...modelsIn(film), ...modelsIn(stt)]);
  const authoring = [...recorded].filter((m) => m.startsWith('claude-'));
  const sttModels = [...modelsIn(stt)];
  const fontsCss = path.resolve(P.dir, '../../public/fonts/film/fonts.css');
  const fonts = fs.existsSync(fontsCss) ? [...new Set([...fs.readFileSync(fontsCss, 'utf8').matchAll(/font-family:\s*'([^']+)'/g)].map((m) => m[1]))].sort() : [];

  const voiceName = String(voice?.name ?? '').split(' — ')[0].trim() || 'a Voice Library voice';
  const roles = [
    {
      role: 'Research, script, animation code and music code',
      credit: authoring.length ? authoring.map(nice).join(', ') : 'Claude Opus 5.5 (Anthropic)',
      detail: 'Every fact traced to a cited source; every line, shot and Strudel cue written at high reasoning effort. Anthropic is a lab in this story, held to the same sources and standard as every other.',
    },
    {
      role: 'Narration voice',
      credit: `ElevenLabs — “${voiceName}”${voice?.model ? ` · ${nice(voice.model)}` : ''}`,
      detail: 'A library voice chosen by audition; not a clone or imitation of any real person.',
    },
    ...(sttModels.length ? [{ role: 'Pronunciation checks', credit: sttModels.map(nice).join(', '), detail: 'Speech-to-text round trip on every name the voice might mangle.' }] : []),
    {
      role: 'Music',
      credit: `Strudel (strudel.cc) — ${cues.length} cues`,
      detail: 'Composed as live-coding patterns by Claude and rendered with Strudel’s own Export to WAV. Each cue’s source opens in strudel.cc from the film page.',
    },
    ...(fs.existsSync(path.join(P.score.dir, 'foley.json'))
      ? [{ role: 'Sound effects', credit: `Synthesized in code — ${(readJson(path.join(P.score.dir, 'foley.json'), {}).events ?? []).length} foley events`, detail: 'Lamp clicks, match strikes and stamps generated by generator/film/lib/foley.mjs; no sample libraries.' }]
      : []),
    { role: 'Picture', credit: 'Canvas 2D in the browser', detail: 'Painted live, frame by frame; the shelf plays the same code that renders the film.' },
    { role: 'Render and mix', credit: 'Chromium (headless) · FFmpeg (x264, AAC)' },
    ...(fonts.length ? [{ role: 'Type', credit: fonts.join(' · ') }] : []),
  ];

  const cueCredits = cues
    .map((c) => {
      const file = c.file ? path.join(P.dir, c.file) : path.join(P.score.cueDir, `${c.id}.strudel`);
      if (!fs.existsSync(file)) return null;
      const code = fs.readFileSync(file, 'utf8');
      return { id: c.id, title: cueTitle(code, c.id), start: c.start, end: c.end, mood: c.mood ?? null, chars: code.length, url: strudelLink(code) };
    })
    .filter(Boolean)
    .sort((a, b) => a.start - b.start);

  // the film's end card: one short line per role (the page carries details, fonts and the strudel.cc links)
  const card = [
    `Research, script & code — ${authoring.length ? authoring.map(nice).join(', ').replace(' (Anthropic)', ' · Anthropic') : 'Claude Opus 5.5 · Anthropic'}`,
    `Voice — ElevenLabs · “${voiceName}”`,
    ...(sttModels.length ? [`Pronunciation checks — ${sttModels.map(nice).join(', ')}`] : []),
    `Music — Strudel · strudel.cc`,
    ...(roles.some((r) => r.role === 'Sound effects') ? ['Sound effects — synthesized in code'] : []),
    'Picture — Canvas 2D in the browser',
    'Render & mix — Chromium · FFmpeg',
  ];
  // footer lines under the card: the maker disclosure first (the film covers Anthropic's founding, disputes and
  // settlement, so the picture itself must say Claude's maker is a party to this story), then the pointer to the page
  const footer = [
    ...(authoring.some((m) => m.startsWith('claude-')) || !authoring.length ? ['Claude is made by Anthropic, a lab in this story, held to the same sources as every other.'] : []),
    'Every music cue’s Strudel source: on the film’s page',
  ];
  return { version: 1, slug, roles, card, footer, cues: cueCredits };
}
