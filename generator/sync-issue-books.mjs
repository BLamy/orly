// Keep the "tweak a book" issue form's book dropdown in sync with the library.
// The dropdown options live between BOOKS:START / BOOKS:END markers in
// .github/ISSUE_TEMPLATE/tweak-book.yml.
//   node generator/sync-issue-books.mjs           # rewrite the dropdown
//   node generator/sync-issue-books.mjs --check    # exit 1 if out of sync (pre-commit)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LIB = join(ROOT, 'public', 'generated', 'library.json');
const FORM = join(ROOT, '.github', 'ISSUE_TEMPLATE', 'tweak-book.yml');
const START = '# BOOKS:START (auto-generated by generator/sync-issue-books.mjs — do not edit by hand)';
const END = '# BOOKS:END';

function optionLines(libPath = LIB) {
  if (!existsSync(libPath)) return [];
  const { books = [] } = JSON.parse(readFileSync(libPath, 'utf8'));
  return books
    .filter((b) => b.slug)
    .map((b) => {
      const label = `${b.title || b.slug}${b.subtitle ? ` · ${b.subtitle}` : ''} — ${b.slug}`;
      return `        - ${JSON.stringify(label)}`; // JSON.stringify → safely quoted/escaped
    });
}

// Replace the marker block in the form text with the given option lines.
function withOptions(text, lines) {
  const block = [`        ${START}`, ...lines, `        ${END}`].join('\n');
  const re = new RegExp(`[ \\t]*${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);
  return text.replace(re, block);
}

export function syncIssueBooks({ libPath = LIB, formPath = FORM } = {}) {
  if (!existsSync(formPath)) return false; // form not created yet — nothing to sync
  const text = readFileSync(formPath, 'utf8');
  const next = withOptions(text, optionLines(libPath));
  if (next !== text) writeFileSync(formPath, next);
  return next !== text;
}

// true if the form's dropdown already matches the library
export function isInSync({ libPath = LIB, formPath = FORM } = {}) {
  if (!existsSync(formPath)) return true;
  const text = readFileSync(formPath, 'utf8');
  return withOptions(text, optionLines(libPath)) === text;
}

// run directly?
if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes('--check');
  if (check) {
    if (isInSync()) process.exit(0);
    console.error('✗ tweak-book.yml book dropdown is out of sync with library.json.');
    console.error('  Fix it with: node generator/sync-issue-books.mjs');
    process.exit(1);
  }
  const changed = syncIssueBooks();
  console.error(changed ? '✓ updated tweak-book.yml book dropdown' : '✓ tweak-book.yml already up to date');
}
