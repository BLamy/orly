#!/usr/bin/env node
// Generate docs/film/kit-catalog.md from the film kit's module header comments and exports.
//   node tools/film/kit-catalog.mjs
// Re-run whenever the kit changes; writers and animators read the catalogue, not the source.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const KIT = path.join(ROOT, 'apps/bookshelf/src/viz/film/silhouette');
const SECTIONS = [
  ['Palette & moods', ['palette.ts']],
  ['Atmosphere', ['atmosphere.ts']],
  ['Finish', ['finish.ts']],
  ['Transitions', ['transitions.ts']],
  ['Typography', ['type.ts', 'overlays.tsx']],
  ['Ornament & lathe', ['ornament.ts', 'lathe.ts']],
  ['Architecture (sets)', ['architecture']],
  ['Nature', ['nature']],
  ['Props & machines', ['props']],
  ['Puppets', ['puppet']],
  ['Teaching machines (metaphors)', ['metaphors']],
];

const files = (p) => {
  const abs = path.join(KIT, p);
  if (statSync(abs).isDirectory())
    return readdirSync(abs).filter((f) => /\.(ts|tsx)$/.test(f) && !f.startsWith('_')).sort((a, b) => (a === 'index.ts' ? -1 : b === 'index.ts' ? 1 : a.localeCompare(b))).map((f) => path.join(abs, f));
  return [abs];
};
const header = (src) => {
  const m = src.match(/^\s*\/\*\*([\s\S]*?)\*\//);
  return m ? m[1].split('\n').map((l) => l.replace(/^\s*\* ?/, '')).join('\n').trim() : '';
};
const exportsOf = (src) => [...src.matchAll(/^export\s+(?:const|function|class)\s+([A-Za-z0-9_$]+)/gm)].map((m) => m[1]);

const out = [
  '# Film kit catalogue',
  '',
  '_Generated by `tools/film/kit-catalog.mjs` from module headers; do not edit by hand._',
  '',
  'Everything is importable from `apps/bookshelf/src/viz/film` (the barrel). Painters are `(c, opts, env: PaintEnv)` and draw in the',
  'current layer\'s rest-screen coordinates; see the `film-shot` skill for the shot contract and paint order. Galleries for every',
  'piece: `http://127.0.0.1:5199/film-gallery.html?g=<name>` (`npm run film:dev`).',
  '',
];
for (const [title, parts] of SECTIONS) {
  out.push(`## ${title}`, '');
  for (const f of parts.flatMap(files)) {
    const src = readFileSync(f, 'utf8');
    const rel = path.relative(path.join(ROOT, 'apps/bookshelf/src/viz/film'), f);
    const ex = exportsOf(src);
    const h = header(src);
    if (!h && !ex.length) continue;
    out.push(`### \`${rel}\``, '');
    if (h) out.push(h.length > 2200 ? h.slice(0, 2200) + ' …' : h, '');
    if (ex.length) out.push(`Exports: ${ex.map((e) => `\`${e}\``).join(', ')}`, '');
  }
}
writeFileSync(path.join(ROOT, 'docs/film/kit-catalog.md'), out.join('\n'));
console.log(`wrote docs/film/kit-catalog.md (${out.length} lines)`);
